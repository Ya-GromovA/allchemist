class User(Base):
    """A person with an account. The single source of identity truth."""

    __tablename__ = "users"

    user_id: Mapped[str] = mapped_column(Text, primary_key=True)
    status: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("'active'"))
    display_name: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    is_demo: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("false"))
    is_test: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("false"))
    created_at: Mapped[datetime] = mapped_column(TZ, nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(TZ, nullable=False, server_default=func.now())
    last_login_at: Mapped[Optional[datetime]] = mapped_column(TZ, nullable=True)
    deleted_at: Mapped[Optional[datetime]] = mapped_column(TZ, nullable=True)

    identifiers: Mapped[list["UserIdentifier"]] = relationship(
        back_populates="user", cascade="all, delete-orphan", passive_deletes=True
    )
    credential: Mapped[Optional["UserCredential"]] = relationship(
        back_populates="user", cascade="all, delete-orphan", passive_deletes=True, uselist=False
    )
    sessions: Mapped[list["UserSession"]] = relationship(
        back_populates="user", cascade="all, delete-orphan", passive_deletes=True
    )
    role_assignments: Mapped[list["RoleAssignment"]] = relationship(
        back_populates="user", cascade="all, delete-orphan", passive_deletes=True
    )
    consents: Mapped[list["Consent"]] = relationship(
        back_populates="user",
        cascade="all, delete-orphan",
        passive_deletes=True,
        foreign_keys="Consent.user_id",
    )

    __table_args__ = (
        CheckConstraint(_in_list("status", USER_STATUSES), name="users_status_check"),
        CheckConstraint(
            "(status <> 'deleted'::text) OR (deleted_at IS NOT NULL)",
            name="users_deleted_at_check",
        ),
        Index("idx_users_status", "status"),
    )


class UserIdentifier(Base):
    """A login, phone number or e-mail address that resolves to one account.

    ``value_normalized`` is what uniqueness is enforced on: logins lower-cased,
    phones reduced to digits with a leading ``+``. ``value`` keeps what the user
    actually typed.
    """

    __tablename__ = "user_identifiers"

    identifier_id: Mapped[str] = mapped_column(UUID(as_uuid=False), primary_key=True, server_default=_UUID_PK)
    user_id: Mapped[str] = mapped_column(
        Text, ForeignKey("users.user_id", ondelete="CASCADE"), nullable=False
    )
    kind: Mapped[str] = mapped_column(Text, nullable=False)
    value: Mapped[str] = mapped_column(Text, nullable=False)
    value_normalized: Mapped[str] = mapped_column(Text, nullable=False)
    is_primary: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("false"))
    verified_at: Mapped[Optional[datetime]] = mapped_column(TZ, nullable=True)
    created_at: Mapped[datetime] = mapped_column(TZ, nullable=False, server_default=func.now())

    user: Mapped["User"] = relationship(back_populates="identifiers")

    __table_args__ = (
        CheckConstraint(_in_list("kind", IDENTIFIER_KINDS), name="user_identifiers_kind_check"),
        UniqueConstraint("kind", "value_normalized", name="uq_user_identifiers_kind_value"),
        Index("idx_user_identifiers_user", "user_id"),
        Index(
            "uq_user_identifiers_primary",
            "user_id",
            "kind",
            unique=True,
            postgresql_where=text("is_primary"),
        ),
    )


