"""Identity and access model.

This is the part of the schema that did not exist before revision ``0002``:
until then identity lived in ``backend/data/user_state.json`` -- a single file
rewritten in full on every login, with no constraints, no transactions and no
referential integrity.

The access chain implemented on top of these tables is

    role -> permission -> ownership -> tenant -> scope -> licence -> flag ->
    publication status

and deny always wins. Each link is a real table with real constraints, so a
missing link is a failed foreign key rather than a missing ``if``.

Design decisions worth keeping in mind when extending this module:

* ``users.user_id`` stays ``text``. Production already carries opaque ids
  (``u_invite_001122``, ``admin_console``) in ten tables and in issued JWTs;
  swapping them for UUIDs would invalidate every live session and every stored
  reference for no functional gain.
* Identifiers (login / phone / e-mail) are rows, not columns: four accounts
  already have two logins each, and a column cannot hold that.
* Passwords are Argon2id for anything set from now on. The two legacy families
  (bcrypt, pbkdf2_sha256) are preserved as-is and marked ``needs_rehash`` so the
  next successful login upgrades them; nobody is locked out by the migration.
* ``audit_log`` and ``auth_attempt_events`` are append-only, enforced by a
  trigger in the database rather than by convention in the service layer.
"""

