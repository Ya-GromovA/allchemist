class RefreshToken(Base):
    """One link of a refresh-token rotation chain.

    Only the SHA-256 of the token is stored. ``replaced_by_token_id`` makes
    replay detectable: presenting a token that already has a successor means the
    chain forked, and the whole session is revoked.
    """

    __tablename__ = "refresh_tokens"

    token_id: Mapped[str] = mapped_column(UUID(as_uuid=False), primary_key=True, server_default=_UUID_PK)
    session_id: Mapped[str] = mapped_column(
        Text, ForeignKey("user_sessions.session_id", ondelete="CASCADE"), nullable=False
    )
    token_hash: Mapped[str] = mapped_column(Text, nullable=False)
    issued_at: Mapped[datetime] = mapped_column(TZ, nullable=False, server_default=func.now())
    expires_at: Mapped[datetime] = mapped_column(TZ, nullable=False)
    used_at: Mapped[Optional[datetime]] = mapped_column(TZ, nullable=True)
    replaced_by_token_id: Mapped[Optional[str]] = mapped_column(
        UUID(as_uuid=False), ForeignKey("refresh_tokens.token_id", ondelete="SET NULL"), nullable=True
    )
    revoked_at: Mapped[Optional[datetime]] = mapped_column(TZ, nullable=True)

    session: Mapped["UserSession"] = relationship(
        back_populates="refresh_tokens", foreign_keys=[session_id]
    )

    __table_args__ = (
        UniqueConstraint("token_hash", name="uq_refresh_tokens_token_hash"),
        Index("idx_refresh_tokens_session", "session_id"),
    )


