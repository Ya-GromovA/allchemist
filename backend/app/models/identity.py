class RoleAssignment(Base):
    """A role held by a user **within a scope**.

    A teacher is not "a teacher": they are a teacher *of class 9IT at site
    Novaya Zvezda of school 2070*. The scope columns are real foreign keys, so
    an assignment can never point at a class that does not exist, and the CHECK
    constraint makes the scope type and the filled-in scope column agree.
    """

    __tablename__ = "role_assignments"

    assignment_id: Mapped[str] = mapped_column(UUID(as_uuid=False), primary_key=True, server_default=_UUID_PK)
    user_id: Mapped[str] = mapped_column(
        Text, ForeignKey("users.user_id", ondelete="CASCADE"), nullable=False
    )
    role_key: Mapped[str] = mapped_column(Text, ForeignKey("roles.role_key"), nullable=False)
    scope_type: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("'global'"))
    organization_id: Mapped[Optional[str]] = mapped_column(
        Text, ForeignKey("organizations.organization_id"), nullable=True
    )
    school_id: Mapped[Optional[str]] = mapped_column(
        Text, ForeignKey("schools.school_id"), nullable=True
    )
    site_id: Mapped[Optional[str]] = mapped_column(
        Text, ForeignKey("school_sites.site_id"), nullable=True
    )
    class_id: Mapped[Optional[str]] = mapped_column(
        Text, ForeignKey("school_classes.class_id"), nullable=True
    )
    subject: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    granted_by: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    granted_at: Mapped[datetime] = mapped_column(TZ, nullable=False, server_default=func.now())
    expires_at: Mapped[Optional[datetime]] = mapped_column(TZ, nullable=True)
    revoked_at: Mapped[Optional[datetime]] = mapped_column(TZ, nullable=True)
    revoked_reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    user: Mapped["User"] = relationship(back_populates="role_assignments")

    __table_args__ = (
        CheckConstraint(_in_list("scope_type", SCOPE_TYPES), name="role_assignments_scope_type_check"),
        CheckConstraint(
            "(scope_type = 'global'::text AND organization_id IS NULL AND school_id IS NULL "
            "AND site_id IS NULL AND class_id IS NULL) "
            "OR (scope_type = 'organization'::text AND organization_id IS NOT NULL) "
            "OR (scope_type = 'school'::text AND school_id IS NOT NULL) "
            "OR (scope_type = 'site'::text AND site_id IS NOT NULL) "
            "OR (scope_type = 'class'::text AND class_id IS NOT NULL)",
            name="role_assignments_scope_shape_check",
        ),
        Index("idx_role_assignments_user", "user_id"),
        Index("idx_role_assignments_school", "school_id"),
        Index("idx_role_assignments_organization", "organization_id"),
        Index("idx_role_assignments_class", "class_id"),
        Index(
            "uq_role_assignments_active",
            "user_id",
            "role_key",
            "scope_type",
            text("COALESCE(organization_id, ''::text)"),
            text("COALESCE(school_id, ''::text)"),
            text("COALESCE(site_id, ''::text)"),
            text("COALESCE(class_id, ''::text)"),
            text("COALESCE(subject, ''::text)"),
            unique=True,
            postgresql_where=text("revoked_at IS NULL"),
        ),
    )


